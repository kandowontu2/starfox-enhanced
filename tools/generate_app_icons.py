#!/usr/bin/env python3
"""Regenerate checked-in icons from assets/icons/source.png (requires Pillow).

Ordinary game builds use the checked-in outputs, without image dependencies.
No redraw, stretching or cropping: wide tiles letterbox the full artwork.
"""
import argparse
from io import BytesIO
from pathlib import Path
import struct
import zlib
from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "assets/icons"
IOS = {"AppIcon60@2x.png": 120, "AppIcon60@3x.png": 180,
       "AppIcon76.png": 76, "AppIcon76@2x.png": 152, "AppIcon83.5@2x.png": 167}
UWP = {"StoreLogo.png": (50, 50), "Square44x44Logo.png": (44, 44),
       "Square150x150Logo.png": (150, 150), "Wide310x150Logo.png": (310, 150),
       "SplashScreen.png": (620, 300)}
VITA = {"sce_sys/icon0.png": (128, 128), "sce_sys/livearea/contents/bg.png": (840, 500),
        "sce_sys/livearea/contents/startup.png": (280, 158)}


def fitted(source, size, opaque=False):
    result = Image.new("RGBA", size, (0, 0, 0, 255 if opaque else 0))
    image = ImageOps.contain(source, size, Image.Resampling.LANCZOS)
    result.alpha_composite(image, ((size[0] - image.width) // 2, (size[1] - image.height) // 2))
    return result.convert("RGB") if opaque else result


def chunk(kind, payload):
    return (struct.pack(">I", len(payload)) + kind + payload
            + struct.pack(">I", zlib.crc32(kind + payload) & 0xffffffff))


def indexed_png(image):
    # Vita requires opaque 8-bit indexed PNG, not a 1/2/4-bit palette or RGBA.
    image = image.quantize(colors=256, method=Image.Quantize.MEDIANCUT)
    width, height = image.size
    raw = image.tobytes()
    rows = b"".join(b"\0" + raw[y * width:(y + 1) * width] for y in range(height))
    return (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", width, height, 8, 3, 0, 0, 0))
            + chunk(b"PLTE", bytes(image.getpalette()))
            + chunk(b"IDAT", zlib.compress(rows, 9)) + chunk(b"IEND", b""))


def generate():
    with Image.open(ASSETS / "source.png") as original:
        source = original.convert("RGBA")
    if source.size != (512, 512):
        raise ValueError("Expected the owner's unchanged 512x512 source artwork")
    for platform, entries in (("ios", IOS), ("uwp", UWP), ("vita", VITA)):
        for name, size in entries.items():
            if isinstance(size, int): size = (size, size)
            path = ASSETS / platform / name
            path.parent.mkdir(parents=True, exist_ok=True)
            image = fitted(source, size, opaque=True)
            if platform == "vita": path.write_bytes(indexed_png(image))
            else: image.save(path, optimize=True)
    fitted(source, (256, 256)).save(ASSETS / "starfox-enhanced.ico",
        sizes=[(n, n) for n in (16, 24, 32, 48, 64, 128, 256)])
    payload = bytearray()
    for kind, size in ((b"icp4", 16), (b"icp5", 32), (b"icp6", 64),
                       (b"ic07", 128), (b"ic08", 256), (b"ic09", 512), (b"ic10", 1024)):
        buffer = BytesIO()
        fitted(source, (size, size)).save(buffer, format="PNG", optimize=True)
        data = buffer.getvalue()
        payload.extend(kind + struct.pack(">I", len(data) + 8) + data)
    (ASSETS / "starfox-enhanced.icns").write_bytes(b"icns" + struct.pack(">I", len(payload) + 8) + payload)
    fitted(source, (256, 256), opaque=True).save(ASSETS / "switch.jpg", quality=95, subsampling=0)
    fitted(source, (512, 512), opaque=True).save(ROOT / "platform/ps5/sce_sys/icon0.png", optimize=True)
    android = ASSETS / "android"
    for density, size in (("mdpi", 48), ("hdpi", 72), ("xhdpi", 96), ("xxhdpi", 144), ("xxxhdpi", 192)):
        path = android / ("mipmap-" + density) / "ic_launcher.png"
        path.parent.mkdir(parents=True, exist_ok=True)
        fitted(source, (size, size), opaque=True).save(path, optimize=True)
    # The safe zone is a 66dp DIAMETER circle, not a 66dp square. A 46dp
    # square fits inside it, preserving every letter even on round launchers.
    foreground = Image.new("RGBA", (432, 432))
    foreground.alpha_composite(fitted(source, (184, 184)), (124, 124))
    path = android / "drawable-nodpi/ic_launcher_foreground.png"
    path.parent.mkdir(parents=True, exist_ok=True)
    foreground.save(path, optimize=True)
    buffer = BytesIO()
    fitted(source, (128, 128)).save(buffer, format="PNG", optimize=True)
    data = buffer.getvalue()
    lines = [",".join(str(n) for n in data[i:i + 24]) for i in range(0, len(data), 24)]
    (ASSETS / "window-icon.hpp").write_text(
        "// Generated by tools/generate_app_icons.py; do not edit.\n#pragma once\n"
        "inline constexpr unsigned char starfox_window_icon_png[] = {\n"
        + ",\n".join(lines) + "\n};\n", encoding="utf-8")


if __name__ == "__main__":
    argparse.ArgumentParser(description=__doc__).parse_args()
    generate()
