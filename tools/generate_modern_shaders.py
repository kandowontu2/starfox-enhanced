"""Offline SDL_GPU shaders for MODERN (SPIR-V, DXIL and Metal); no runtime compiler.

Metal (MSL) is cross-compiled from each stage's SPIR-V with SPIRV-Cross, as
upstream's portable shaders are (tools/generate_portable_shadows.py). SDL_GPU's
Metal backend binds resources by kind in a fixed order (SDL_gpu.h,
SDL_CreateGPUShader and SDL_CreateGPUComputePipeline, SDL 3.4):
  graphics: [[buffer]] uniform buffers, then storage buffers;
            [[texture]] sampled textures, then storage textures;
            [[sampler]] the same index as its sampled texture.
  compute:  [[buffer]] uniform buffers, read-only then read-write storage
            buffers; [[texture]] sampled, read-only storage, then read-write
            storage textures.
The offsets are the counts the loader declares, so each stage below lists the
same counts as its loader (src/modern/sdl_*.cpp). Every resource's SPIR-V
Binding is rewritten to its Metal slot, then --msl-decoration-binding emits
those slots verbatim; the result is checked against SPIRV-Cross reflection.
Entry points keep their HLSL names (SPIRV-Cross renames only "main" to
"main0"); the header records each one as msl_<stage>_entry.

Generation: python tools/generate_modern_shaders.py --dxc DXC --spirv-cross SPIRV_CROSS
(on Windows the llvm-mingw-built spirv-cross needs llvm-mingw's bin on PATH).
"""
import argparse
import json
import pathlib
import re
import struct
import subprocess
import tempfile
from portable_shader_source import source_digest

parser = argparse.ArgumentParser()
parser.add_argument('--dxc')
parser.add_argument('--spirv-cross')
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
root = pathlib.Path(__file__).resolve().parents[1]
# Bumped whenever the Metal payload format or slot rules change, so --check
# rejects headers generated by an older version of this script.
metal_stamp = '// Metal: SDL_GPU slots v1 (SPIRV-Cross --msl-decoration-binding, MSL 2.1)'
# Resource counts exactly as each loader declares them. Graphics: samplers,
# storage textures, storage buffers, uniform buffers. Compute: samplers,
# read-only storage textures and buffers, read-write storage textures and
# buffers, uniform buffers.
scene_vertex = {'samplers': 0, 'storage_textures': 0, 'storage_buffers': 1, 'uniform_buffers': 2}
scene_fragment = {'samplers': 0, 'storage_textures': 0, 'storage_buffers': 3, 'uniform_buffers': 2}
# (source, stages (name, profile, entry, defines, counts), namespace, extra lines)
shaders = [
    ('scene_sdl', [('vertex', 'vs_6_0', 'sdl_vertex_textured_main', [], scene_vertex),
                   ('fragment', 'ps_6_0', 'sdl_fragment_main', ['-D', 'STARFOX_SDL_FRAGMENT'], scene_fragment)],
     'starfox::modern::shader',
     'inline constexpr const char* vertex_entry="sdl_vertex_textured_main";\n'
     'inline constexpr const char* fragment_entry="sdl_fragment_main";\n'),
    ('layer_filter', [('compute', 'cs_6_0', 'filter_main', ['-D', 'STARFOX_LAYER_FILTER_COMPUTE'],
                       {'samplers': 0, 'readonly_storage_textures': 1, 'readonly_storage_buffers': 1,
                        'readwrite_storage_textures': 1, 'readwrite_storage_buffers': 0, 'uniform_buffers': 1}),
                      ('vertex', 'vs_6_0', 'composite_vertex', [],
                       {'samplers': 0, 'storage_textures': 0, 'storage_buffers': 0, 'uniform_buffers': 0}),
                      ('fragment', 'ps_6_0', 'composite_fragment', [],
                       {'samplers': 1, 'storage_textures': 0, 'storage_buffers': 0, 'uniform_buffers': 1})],
     'starfox::modern::layer_filter_shader', ''),
    ('ray_shadow', [('compute', 'cs_6_0', 'main', [],
                     {'samplers': 0, 'readonly_storage_textures': 0, 'readonly_storage_buffers': 2,
                      'readwrite_storage_textures': 0, 'readwrite_storage_buffers': 2, 'uniform_buffers': 1})],
     'starfox::modern::ray_shadow_shader', ''),
]


def metal_slot(stage, counts, descriptor_set, binding):
    """(namespace, index) SDL_GPU's Metal backend uses for SDL's SPIR-V (set, binding).

    namespace is 'texture' for sampled/storage textures (a sampler shares its
    sampled texture's index) and 'buffer' for uniform and storage buffers."""
    if stage in ('vertex', 'fragment'):
        storage, uniform = (0, 1) if stage == 'vertex' else (2, 3)
        textures = counts['samplers'] + counts['storage_textures']
        if descriptor_set == uniform and binding < counts['uniform_buffers']:
            return 'buffer', binding
        if descriptor_set == storage and binding < textures:
            return 'texture', binding
        if descriptor_set == storage and binding - textures < counts['storage_buffers']:
            return 'buffer', counts['uniform_buffers'] + binding - textures
    else:
        readonly = counts['samplers'] + counts['readonly_storage_textures']
        if descriptor_set == 0 and binding < readonly:
            return 'texture', binding
        if descriptor_set == 0 and binding - readonly < counts['readonly_storage_buffers']:
            return 'buffer', counts['uniform_buffers'] + binding - readonly
        if descriptor_set == 1 and binding < counts['readwrite_storage_textures']:
            return 'texture', readonly + binding
        if descriptor_set == 1 and binding - counts['readwrite_storage_textures'] < counts['readwrite_storage_buffers']:
            return 'buffer', (counts['uniform_buffers'] + counts['readonly_storage_buffers']
                              + binding - counts['readwrite_storage_textures'])
        if descriptor_set == 2 and binding < counts['uniform_buffers']:
            return 'buffer', binding
    raise RuntimeError(f'{stage}: SPIR-V set {descriptor_set} binding {binding} is outside the loader\'s declared counts {counts}')


def rebind_spirv(blob, stage, counts):
    """Copy of the SPIR-V with each Binding decoration replaced by its Metal slot."""
    words = list(struct.unpack(f'<{len(blob) // 4}I', blob))
    if len(blob) % 4 or words[0] != 0x07230203:
        raise RuntimeError('Not a little-endian SPIR-V module')
    sets, bindings = {}, {}
    at = 5
    while at < len(words):
        count, opcode = words[at] >> 16, words[at] & 0xffff
        if count == 0:
            raise RuntimeError('Malformed SPIR-V instruction')
        if opcode == 71 and count >= 4:  # OpDecorate target decoration literal
            if words[at + 2] == 34:  # DescriptorSet
                sets[words[at + 1]] = words[at + 3]
            elif words[at + 2] == 33:  # Binding
                bindings[words[at + 1]] = at + 3
        at += count
    for target, word in bindings.items():
        if target not in sets:
            raise RuntimeError('SPIR-V binding without a descriptor set')
        words[word] = metal_slot(stage, counts, sets[target], words[word])[1]
    return struct.pack(f'<{len(words)}I', *words)


def expected_metal_bindings(reflection, stage, counts):
    expected = set()
    kinds = {'ubos': ('buffer',), 'ssbos': ('buffer',), 'separate_images': ('texture',), 'images': ('texture',),
             'separate_samplers': ('sampler',), 'textures': ('texture', 'sampler')}
    for category, attributes in kinds.items():
        for resource in reflection.get(category, []):
            namespace, index = metal_slot(stage, counts, resource['set'], resource['binding'])
            if namespace != ('buffer' if attributes == ('buffer',) else 'texture'):
                raise RuntimeError(f'{stage}: {resource["name"]} ({category}) falls in SDL\'s {namespace} range')
            expected.update((attribute, index) for attribute in attributes)
    unsupported = [key for key in ('push_constants', 'subpass_inputs', 'acceleration_structures') if reflection.get(key)]
    if unsupported:
        raise RuntimeError(f'{stage}: resources SDL_GPU cannot bind on Metal: {unsupported}')
    return expected


def cross_compile_metal(spirv_cross, temporary, stage, entry, blob, counts):
    directory = pathlib.Path(temporary)
    original = directory / f'{stage}.sdl.spv'
    original.write_bytes(blob)
    rebound = directory / f'{stage}.metal.spv'
    rebound.write_bytes(rebind_spirv(blob, stage, counts))
    reflection_path = directory / f'{stage}.json'
    msl_path = directory / f'{stage}.msl'
    # Reflect SDL's own (set, binding) layout, before the rewrite.
    subprocess.run([spirv_cross, str(original), '--reflect', '--output', str(reflection_path)], check=True)
    subprocess.run([spirv_cross, str(rebound), '--msl', '--msl-version', '20100', '--msl-decoration-binding',
                    '--output', str(msl_path)], check=True)
    reflection = json.loads(reflection_path.read_text())
    # SPIRV-Cross emits whitespace-only lines in its MSL template. Normalize
    # them before embedding so generated headers pass git's whitespace check.
    metal = '\n'.join(line.rstrip() for line in msl_path.read_text().splitlines()) + '\n'
    kind = {'vertex': 'vertex', 'fragment': 'fragment', 'compute': 'kernel'}[stage]
    entries = list(re.finditer(r'^' + kind + r'\s+[\w:<>, ]+?\s+(\w+)\((.*)$', metal, re.MULTILINE))
    if len(entries) != 1:
        raise RuntimeError(f'{stage}: expected one {kind} entry point, found {[m[1] for m in entries]}')
    if entries[0][1] != ('main0' if entry == 'main' else entry):
        raise RuntimeError(f'{stage}: unexpected Metal entry point {entries[0][1]}')
    signature = entries[0][2]
    found = {(name, int(index)) for name, index in re.findall(r'\[\[(buffer|texture|sampler)\((\d+)\)\]\]', signature)}
    expected = expected_metal_bindings(reflection, stage, counts)
    if found != expected:
        raise RuntimeError(f'{stage}: Metal bindings {sorted(found)} differ from SDL slots {sorted(expected)}')
    if re.search(r'\bspv\w*(Buffer|Swizzle|Size)\w*\s*\[\[buffer', metal) or re.search(r'\bdouble\b', metal):
        raise RuntimeError(f'{stage}: MSL needs auxiliary buffers or fp64, which SDL_GPU cannot provide')
    return metal, entries[0][1]


for name, stages, namespace, extra in shaders:
    source = root / f'src/modern/shaders/{name}.hlsl'
    output = root / f'src/modern/shaders/generated/{name}.hpp'
    stamp = '// Source SHA-256: ' + source_digest(source)
    if args.check:
        text = output.read_text() if output.exists() else ''
        if stamp not in text.splitlines()[:3] or metal_stamp not in text.splitlines()[:4]:
            raise SystemExit(f'MODERN {name} shaders stale; run tools/generate_modern_shaders.py --dxc DXC --spirv-cross SPIRV_CROSS.')
        for stage, *_ in stages:
            if f'inline constexpr char msl_{stage}[]=' not in text or f'msl_{stage}_entry=' not in text:
                raise SystemExit(f'MODERN {name} shaders lack Metal {stage}; regenerate with --spirv-cross.')
        if '#if defined(__APPLE__)' not in text:
            raise SystemExit(f'MODERN {name} Metal payload guards are stale; regenerate.')
        continue
    if not args.dxc or not args.spirv_cross:
        parser.error('--dxc and --spirv-cross required for generation')
    text = ('// Generated by tools/generate_modern_shaders.py; do not edit.\n' + stamp + '\n' + metal_stamp
            + '\n#pragma once\n' f'namespace {namespace} {{\n')
    metal_text = ''
    with tempfile.TemporaryDirectory() as temporary:
        for stage, profile, entry, defines, counts in stages:
            for target, flags in (('spirv', ['-spirv', '-fspv-target-env=vulkan1.0']), ('dxil', [])):
                binary = pathlib.Path(temporary) / f'{stage}.{target}'
                subprocess.run([args.dxc, *flags, '-Wno-ignored-attributes', *defines, '-T', profile, '-E', entry,
                                '-Fo', str(binary), str(source)], check=True)
                blob = binary.read_bytes()
                text += f'inline constexpr unsigned char {target}_{stage}[]={{\n'
                text += ',\n'.join(','.join(str(b) for b in blob[i:i+32]) for i in range(0, len(blob), 32)) + '\n};\n'
                if target == 'spirv':
                    metal, metal_entry = cross_compile_metal(args.spirv_cross, temporary, stage, entry, blob, counts)
            # Apple only: MSVC (Xbox UWP) rejects raw strings this long, and
            # other platforms never load Metal.
            metal_text += (f'inline constexpr const char* msl_{stage}_entry="{metal_entry}";\n'
                           f'inline constexpr char msl_{stage}[]=R"SFXMETAL(\n' + metal + ')SFXMETAL";\n')
    text += extra + '#if defined(__APPLE__)\n' + metal_text + '#endif\n}\n'
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(text, encoding='utf-8', newline='\n')
