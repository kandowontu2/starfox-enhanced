"""Offline SDL_GPU scene shaders for MODERN (SPIR-V + DXIL); no runtime compiler."""
import argparse
import pathlib
import subprocess
import tempfile
from portable_shader_source import source_digest

parser = argparse.ArgumentParser()
parser.add_argument('--dxc')
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
root = pathlib.Path(__file__).resolve().parents[1]
# (source, stages (name, profile, entry, defines), namespace, extra lines)
shaders = [
    ('scene_sdl', [('vertex', 'vs_6_0', 'sdl_vertex_textured_main', []),
                   ('fragment', 'ps_6_0', 'sdl_fragment_main', ['-D', 'STARFOX_SDL_FRAGMENT'])],
     'starfox::modern::shader',
     'inline constexpr const char* vertex_entry="sdl_vertex_textured_main";\n'
     'inline constexpr const char* fragment_entry="sdl_fragment_main";\n'),
    ('layer_filter', [('compute', 'cs_6_0', 'filter_main', ['-D', 'STARFOX_LAYER_FILTER_COMPUTE']),
                      ('vertex', 'vs_6_0', 'composite_vertex', []),
                      ('fragment', 'ps_6_0', 'composite_fragment', [])],
     'starfox::modern::layer_filter_shader', ''),
    ('ray_shadow', [('compute', 'cs_6_0', 'main', [])], 'starfox::modern::ray_shadow_shader', ''),
]
for name, stages, namespace, extra in shaders:
    source = root / f'src/modern/shaders/{name}.hlsl'
    output = root / f'src/modern/shaders/generated/{name}.hpp'
    stamp = '// Source SHA-256: ' + source_digest(source)
    if args.check:
        if not output.exists() or stamp not in output.read_text().splitlines()[:3]:
            raise SystemExit(f'MODERN {name} shaders stale; run tools/generate_modern_shaders.py --dxc DXC.')
        continue
    if not args.dxc:
        parser.error('--dxc required for generation')
    text = ('// Generated by tools/generate_modern_shaders.py; do not edit.\n' + stamp + '\n#pragma once\n'
            f'namespace {namespace} {{\n')
    with tempfile.TemporaryDirectory() as temporary:
        for stage, profile, entry, defines in stages:
            for target, flags in (('spirv', ['-spirv', '-fspv-target-env=vulkan1.0']), ('dxil', [])):
                binary = pathlib.Path(temporary) / f'{stage}.{target}'
                subprocess.run([args.dxc, *flags, '-Wno-ignored-attributes', *defines, '-T', profile, '-E', entry,
                                '-Fo', str(binary), str(source)], check=True)
                blob = binary.read_bytes()
                text += f'inline constexpr unsigned char {target}_{stage}[]={{\n'
                text += ',\n'.join(','.join(str(b) for b in blob[i:i+32]) for i in range(0, len(blob), 32)) + '\n};\n'
    text += extra + '}\n'
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(text, encoding='utf-8', newline='\n')
